func recordIDs(r *repo, args []string, all bool) ([]string, error) {
	if all {
		return r.Store.List()
	}
	if len(args) == 0 {
		return nil, fmt.Errorf("name the records, or pass --all")
	}
	ids := make([]string, 0, len(args))
	for _, arg := range args {
		rec, _, err := r.resolve(arg)
		if err != nil {
			return nil, err
		}
		ids = append(ids, rec.ID)
	}
	return ids, nil
}

