func stagedTree(r *repo) (string, func(), error) {
	dir, err := os.MkdirTemp("", "provenance-staged-")
	if err != nil {
		return "", nil, err
	}
	cleanup := func() { os.RemoveAll(dir) }
	top, err := r.git("rev-parse", "--show-toplevel")
	if err != nil {
		cleanup()
		return "", nil, err
	}
	if _, err := r.git("-C", top, "checkout-index", "-a", "--prefix="+dir+"/"); err != nil {
		cleanup()
		return "", nil, err
	}
	prefix, err := r.git("rev-parse", "--show-prefix")
	if err != nil {
		cleanup()
		return "", nil, err
	}
	path := dir
	if prefix != "" {
		path = dir + string(os.PathSeparator) + strings.ReplaceAll(prefix, "/", string(os.PathSeparator))
	}
	if err := os.MkdirAll(path, 0o755); err != nil {
		cleanup()
		return "", nil, err
	}
	return path, cleanup, nil
}

