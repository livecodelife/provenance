func searchTerms(s string) []string {
	var terms []string
	for _, w := range strings.FieldsFunc(strings.ToLower(s), func(c rune) bool { return !unicode.IsLetter(c) && !unicode.IsDigit(c) }) {
		if len([]rune(w)) >= 2 && !searchStop[w] {
			terms = append(terms, w)
		}
	}
	return terms
}

