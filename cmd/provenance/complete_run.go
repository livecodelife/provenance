func overlappingSealed(self *record.Record, all []*record.Record, files []string) []*record.Record {
	var out []*record.Record
	for _, rec := range all {
		if rec == self {
			continue
		}
		if rec.Status != record.StatusImplemented || rec.SealedAtSHA == "" {
			continue
		}
		for _, f := range files {
			ok, err := scope.InScope(rec, f)
			if err == nil && ok {
				out = append(out, rec)
				break
			}
		}
	}
	return out
}

