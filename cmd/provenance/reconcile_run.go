func writablePath(r *repo, rel string, always, open []string, restricted bool) bool {
	if isSnapshotFile(r, rel) {
		return false
	}
	if !restricted || scope.Excluded(rel, always) {
		return true
	}
	for _, p := range open {
		if ok, err := scope.Match(rel, p); err == nil && ok {
			return true
		}
	}
	return false
}

