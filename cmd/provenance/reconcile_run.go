func openScope(recs []*record.Record) []string {
	seen := map[string]bool{}
	var out []string
	for _, rec := range recs {
		if rec.Status != record.StatusOpen || scope.Mode(rec) != "allowlist" {
			continue
		}
		for _, p := range rec.AffectedScope {
			if p != "" && !seen[p] {
				seen[p] = true
				out = append(out, p)
			}
		}
	}
	sort.Strings(out)
	return out
}

