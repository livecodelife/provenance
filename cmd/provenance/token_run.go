		fmt.Fprintf(tw, "%s\t%s\t%s\t%s\t%s\t%s\n", t.ID, t.Name, strings.Join(t.Scopes, ","), dash(t.CreatedAt), dash(t.LastUsedAt), dash(t.ExpiresAt))
