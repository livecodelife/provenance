func behindSet(r *repo) map[string]bool {
	set := map[string]bool{}
	shared, _ := loadShared(r)
	found, err := stale.FindShared(r.Store, shared)
	if err != nil {
		return set
	}
	for _, f := range found {
		if f.Kind != stale.Unknown {
			set[f.ID] = true
		}
	}
	return set
}

