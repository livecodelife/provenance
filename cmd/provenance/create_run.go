func runCreate(out io.Writer, cmd *cobra.Command, args []string) error {
	r, err := openRepo(cmd)
	if err != nil {
		return err
	}

	title, _ := cmd.Flags().GetString("title")
	intent, _ := cmd.Flags().GetString("intent")
	typ, _ := cmd.Flags().GetString("type")
	tags, _ := cmd.Flags().GetStringArray("tag")
	scope, _ := cmd.Flags().GetStringArray("scope")
	implements, _ := cmd.Flags().GetString("implements")
	locked, _ := cmd.Flags().GetBool("locked")
	noEdit, _ := cmd.Flags().GetBool("no-edit")
	suffix, _ := cmd.Flags().GetString("id-suffix")

	if typ != "" && !record.Type(typ).Valid(2) {
		return fmt.Errorf("invalid type %q (brief|blueprint|imprint)", typ)
	}

	cleanTags := []string{}
	for _, t := range tags {
		for _, p := range strings.Split(t, ",") {
			p = strings.TrimSpace(p)
			if p != "" {
				cleanTags = append(cleanTags, p)
			}
		}
	}

	taken := map[string]bool{}
	ids, err := r.Store.List()
	if err != nil {
		return err
	}
	for _, existing := range ids {
		taken[existing] = true
		loaded, _, err := r.Store.Load(existing)
		if err != nil {
			continue
		}
		for _, a := range loaded.Aliases {
			taken[a] = true
		}
	}

	id, err := newID(time.Now().Year(), suffix, taken)
	if err != nil {
		return err
	}

	var implementsID, implementsURI string
	var implementsVersion int
	if strings.HasPrefix(implements, "at://") {
		parentID, ok := record.ParseImplementsURI(implements)
		if !ok {
			return fmt.Errorf("invalid --implements %q: want a record id or at://<did>/dev.provisio.provenance.record/<id>", implements)
		}
		implementsID = parentID
		implementsURI = implements
	} else if implements != "" {
		parent, _, err := r.resolve(implements)
		if err != nil {
			return err
		}
		implementsID = parent.ID
		implementsVersion = parent.Version
	}

	if scope == nil {
		scope = []string{}
	}

	rec := &record.Record{
		Schema:            2,
		ID:                id,
		Title:             title,
		Type:              record.Type(typ),
		Status:            record.StatusDraft,
		CreatedAt:         time.Now().Format("2006-01-02"),
		Author:            r.author(),
		Version:           1,
		Intent:            intent,
		Locked:            locked,
		Implements:        implementsID,
		ImplementsURI:     implementsURI,
		ImplementsVersion: implementsVersion,
		Constraints:       []string{},
		AffectedScope:     scope,
		ForbiddenScope:    []string{},
		Related:           []string{},
		AssociatedTraces:  []string{},
		Monitors:          []string{},
		Tags:              cleanTags,
		AssociatedSpecs:   []record.AssociatedSpec{},
	}

	if err := r.Store.Save(rec, nil); err != nil {
		return err
	}

	path := filepath.Join(r.Root, r.recordPath(id))

	if !noEdit {
		editor := os.Getenv("EDITOR")
		if editor == "" {
			editor = "vi"
		}
		c := exec.Command(editor, path)
		c.Stdin = os.Stdin
		c.Stdout = os.Stdout
		c.Stderr = os.Stderr
		if err := c.Run(); err != nil {
			fmt.Fprintf(os.Stderr, "Warning: Could not open editor: %v\n", err)
		}
	}

	fmt.Fprintf(out, "\n✓ Created %s\n\n", path)
	if implementsURI != "" {
		fmt.Fprint(out, "  The parent is in another account, so implements_version is 0 (unpinned); run provenance repin once the parent can be read.\n\n")
	}
	return nil
}

